#ifndef _NET_IF_PFSYNC_H_
#define _NET_IF_PFSYNC_H_

#include <sys/types.h>

/* PFSYNC wire header, retained for IPFW protocol inspection. */
struct pfsync_header {
	u_int8_t version;
	u_int8_t _pad;
	u_int16_t len;
	u_int8_t pfcksum[16];
} __packed;

#endif /* _NET_IF_PFSYNC_H_ */
